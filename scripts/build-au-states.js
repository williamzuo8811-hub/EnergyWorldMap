#!/usr/bin/env node
/* ============================================================
 * 生成 lib/au-states.js（澳大利亚州 / 领地边界 GeoJSON，window.AU_STATES_GEO）
 * ------------------------------------------------------------
 * 来源：Natural Earth 1:50m "Admin 1 – States, Provinces"（公有领域，无需署名），
 *       文件 ne_50m_admin_1_states_provinces.geojson（约 2.3 MB，全球），
 *       可从 https://github.com/nvkelso/natural-earth-vector/tree/master/geojson 下载。
 * 用法：node scripts/build-au-states.js <path/to/ne_50m_admin_1_states_provinces.geojson>
 * 输出：仅保留澳大利亚 9 个要素 → 8 个（Jervis Bay 领地并入 NSW），坐标保留 3 位小数（~100 m），
 *       属性精简为 { abbr, name, en }。零依赖；输出已提交，仅在换源 / 换精度时重跑。
 * ============================================================ */
'use strict';
const fs = require('fs');
const path = require('path');

const src = process.argv[2];
if (!src || !fs.existsSync(src)) {
  console.error('用法：node scripts/build-au-states.js <ne_50m_admin_1_states_provinces.geojson>');
  process.exit(1);
}
const g = JSON.parse(fs.readFileSync(src, 'utf8'));
const ABBR = { NS: 'NSW', VI: 'VIC', QL: 'QLD', SA: 'SA', WA: 'WA', TS: 'TAS', NT: 'NT', CT: 'ACT', JB: 'NSW' };
const ZH = { NSW: '新南威尔士州', VIC: '维多利亚州', QLD: '昆士兰州', SA: '南澳大利亚州', WA: '西澳大利亚州', TAS: '塔斯马尼亚州', NT: '北领地', ACT: '首都领地' };
const EN = { NSW: 'New South Wales', VIC: 'Victoria', QLD: 'Queensland', SA: 'South Australia', WA: 'Western Australia', TAS: 'Tasmania', NT: 'Northern Territory', ACT: 'Australian Capital Territory' };

const au = g.features.filter(f => f.properties && (f.properties.adm0_a3 === 'AUS' || f.properties.admin === 'Australia'));
if (!au.length) { console.error('源文件里没有澳大利亚要素'); process.exit(1); }

const r3 = n => Math.round(n * 1000) / 1000;
const ringR = ring => ring.map(pt => [r3(pt[0]), r3(pt[1])]);
const polys = {};           // abbr → MultiPolygon coords
au.forEach(f => {
  const abbr = ABBR[f.properties.postal];
  if (!abbr) { console.warn('跳过未知要素', f.properties.name, f.properties.postal); return; }
  const geom = f.geometry;
  const list = geom.type === 'Polygon' ? [geom.coordinates] : geom.coordinates;
  polys[abbr] = (polys[abbr] || []).concat(list.map(poly => poly.map(ringR)));
});
const ORDER = ['WA', 'NT', 'SA', 'QLD', 'NSW', 'ACT', 'VIC', 'TAS'];
const features = ORDER.filter(a => polys[a]).map(abbr => ({
  type: 'Feature', properties: { abbr, name: ZH[abbr], en: EN[abbr] },
  geometry: { type: 'MultiPolygon', coordinates: polys[abbr] },
}));
const out = '/* Vendored Australian state / territory borders (Natural Earth 1:50m admin-1, public domain; Jervis Bay merged into NSW).\n'
  + ' * Generated by scripts/build-au-states.js — do not hand-edit. Attaches window.AU_STATES_GEO for au.html. Not project data. */\n'
  + 'window.AU_STATES_GEO = ' + JSON.stringify({ type: 'FeatureCollection', features }) + ';\n';
const dst = path.join(__dirname, '..', 'lib', 'au-states.js');
fs.writeFileSync(dst, out);
console.log('写出', dst, (out.length / 1024).toFixed(1) + ' KB，要素：', features.map(f => f.properties.abbr).join(' '));
